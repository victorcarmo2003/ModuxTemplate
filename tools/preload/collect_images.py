"""Collect every image id written in src/ into src/Preload/client/PreloadController/Images.luau.

Owner 2026-10-18: preload "tudo que foi imagem, tudo que foi assets". Audio ids (Content.Sounds, Content.VoiceLines)
go through the audio LoadQueue and animation ids through AnimController, so they are skipped here. Critical = the
images a scare or the first screens show at once (jumpscare, anomaly looks, horror overlays, HUD icons): the loading
screen waits for them. Everything else loads in the background after the curtain.

Run from the repo root after adding an image id:  python tools/preload/collect_images.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "src"
OUT = SRC / "Preload" / "client" / "PreloadController" / "Images.luau"
SKIP = {
    "src/Shared/Content/Sounds.luau",
    "src/Shared/Content/VoiceLines.luau",
    "src/Shared/Content/Validate.luau",
    "src/Anim/client/AnimController/Clips.luau",
    "src/Preload/client/PreloadController/Images.luau",
}
CRITICAL_PREFIXES = (
    "src/Anomaly/",
    "src/Shared/Content/Security.luau",
    "src/Shared/Content/Atmospheres.luau",
    "src/Interface/client/Components/Icons/",
    "src/Interface/client/Components/AnomalyTablet/",
    "src/Interface/client/Components/Sunburst/",
)
# images drawn by GUI objects (ImageLabel / ImageButton): preloaded through an ImageLabel. A Decal asks for the 3D
# texture representation of the asset, which a UI image may not have ("Asset content representation is being
# generated", checked in Studio 2026-10-18). Everything else is a world texture (MeshPart, Decal, particles).
UI_PREFIXES = (
    "src/Interface/",
    "src/Anomaly/client/AnomalyController/Effects/Kit/Jumpscare.luau",
    "src/Shared/Content/Security.luau",
)
ID = re.compile(r"rbxassetid://(\d+)")


def main() -> None:
    groups: dict[str, dict[str, list[str]]] = {
        "CriticalUi": {}, "CriticalWorld": {}, "BackgroundUi": {}, "BackgroundWorld": {},
    }
    seen: set[str] = set()
    for path in sorted(SRC.rglob("*.luau")):
        rel = path.relative_to(ROOT).as_posix()
        if rel in SKIP or rel.startswith("src/Modux/"):
            continue
        ids = []
        for match in ID.finditer(path.read_text(encoding="utf-8")):
            asset = match.group(1)
            if asset not in seen:
                seen.add(asset)
                ids.append(asset)
        if not ids:
            continue
        when = "Critical" if rel.startswith(CRITICAL_PREFIXES) else "Background"
        kind = "Ui" if rel.startswith(UI_PREFIXES) else "World"
        groups[when + kind][rel] = ids
    lines = [
        "--!strict",
        "-- GENERATED by tools/preload/collect_images.py: do not edit. Every image id written in src/ (audio and",
        "-- animation ids are preloaded by their own queues). Critical = the loading screen waits for them. Ui = drawn by",
        "-- GUI objects (preload through an ImageLabel), World = textures of parts, decals, particles (through a Decal).",
        "export type Images = {",
        "	CriticalUi: { string },",
        "	CriticalWorld: { string },",
        "	BackgroundUi: { string },",
        "	BackgroundWorld: { string },",
        "}",
        "",
        "const IMAGES: Images = {",
    ]
    for name, group in groups.items():
        lines.append(f"\t{name} = {{")
        for rel, ids in group.items():
            lines.append(f"\t\t-- {rel}")
            for asset in ids:
                lines.append(f'\t\t"rbxassetid://{asset}",')
        lines.append("\t},")
    lines += ["}", "", "return table.freeze(IMAGES)", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    counts = ", ".join(f"{name} {sum(len(v) for v in group.values())}" for name, group in groups.items())
    print(f"{counts} -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()

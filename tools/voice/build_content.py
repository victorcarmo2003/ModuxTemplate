"""Build src/Shared/Content/VoiceLines.luau from tools/voice/assets.json + lines.json.

  python build_content.py

Lines.<key> = { Id = "rbxassetid://...", Length = seconds, Speaker }. Only uploaded lines (assetId set, not rejected).
Index["<speaker>\\0<spoken text>"] = key lets Speech find a line without hashing in Luau (spoken text = Speech.Spoken).
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "src", "Shared", "Content", "VoiceLines.luau")
lines = json.load(open(os.path.join(HERE, "lines.json"), encoding="utf-8"))
meta = json.load(open(os.path.join(HERE, "assets.json")))


def lstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\0", "\\x00") + '"'


rows, index = [], []
for k in sorted(meta):
    m = meta[k]
    if not m.get("assetId") or m.get("status") != "ok":
        continue
    rows.append(f'\t{k} = {{ Id = "rbxassetid://{m["assetId"]}", Length = {m["length"]}, Speaker = "{m["speaker"]}" }},')
    index.append(f'\t[{lstr(m["speaker"] + chr(0) + lines[k]["text"])}] = "{k}",')

src = f"""--!strict
-- GENERATED by tools/voice/build_content.py (do not edit by hand). Pre-generated voice lines (Kokoro-82M, AI generated,
-- Apache 2.0; docs/art/credits.md, section Voz). Lines[key] = {{ Id, Length (s), Speaker }}; key = v_<sha1[:10]> of
-- speaker NUL spoken text. Index maps "speaker NUL Speech.Spoken(text)" to the key. A line missing here (or rejected by
-- moderation) falls back to AudioTextToSpeech in Speech.
export type VoiceLine = {{ Id: string, Length: number, Speaker: string }}

const Lines: {{ [string]: VoiceLine }} = {{
{chr(10).join(rows)}
}}

const Index: {{ [string]: string }} = {{
{chr(10).join(index)}
}}

return table.freeze({{ Lines = Lines, Index = Index }})
"""
open(OUT, "w", encoding="utf-8", newline="\n").write(src)
print(len(rows), "lines ->", os.path.normpath(OUT))

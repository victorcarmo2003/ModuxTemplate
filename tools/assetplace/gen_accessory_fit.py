"""Generates src/Crew/shared/AccessoryFit.luau (TASK-089, AST-081 / AST-076; architecture.md §18.9.2).

Source (never edit AccessoryFit.luau by hand; change the source and run this again):
  - Assets/blender/character/AST-081_offsets.json   one entry per kit piece (asset file, R6 anchor, attachment,
                                                     primary species) and the per-species fit of the head pieces
                                                     (hard hat variant / raise, headphones scale / offset, ok flag)
  - gen_crew_looks.SPECIES / CAP_PLAIN               Content.Species keys and the plain-cap species: the hard hat
                                                     variant of every species must agree with the cap (EarsUp)

Output, indexed by Content keys (content-data.md §1.3 rule 8):
  Pivot    scale centre of head pieces (HatAttachment of the rest pose)
  Pieces   kit name -> { Asset, Anchor, Attachment, Only? }  (Only = the one species a shaped piece fits, e.g. masks)
  Species  Content.Species key -> kit name -> { Use?, Offset?, Scale?, Forbidden? }  (only non-default entries)

Usage (repo root):  python tools/assetplace/gen_accessory_fit.py [--check]
  --check  only verifies that the file on disk is up to date (exit 1 if not).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_crew_looks import CAP_PLAIN, SPECIES  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "Assets/blender/character/AST-081_offsets.json"
OUT = ROOT / "src/Crew/shared/AccessoryFit.luau"

# HatAttachment of the rest pose (offsets.json "rules": scale about this point)
PIVOT = (0.0, 6.0, 0.0)
R6 = {"Torso", "Head", "Left Arm", "Right Arm", "Left Leg", "Right Leg"}
# Hand-held pieces: their bbox centre is nearer the leg, so the anchor must be explicit (asset-list AST-081)
HAND = {"Acc_Briefcase": "Right Arm", "Acc_Cane": "Right Arm"}
HARD_HAT = "Acc_HardHat"
EARS_UP_HAT = "Acc_HardHat_EarsUp"


def num(v: float) -> str:
    s = f"{float(v):.3f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def vec(v: list[float]) -> str:
    return f"Vector3.new({', '.join(num(x) for x in v)})"


def lua_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def build() -> str:
    data = json.loads(SRC.read_text(encoding="utf-8"))
    problems: list[str] = []
    key_of = {asset: key for key, asset in SPECIES.items()}

    pieces: dict = data["pieces"]
    lines: list[str] = []
    w = lines.append
    w("--!strict")
    w("-- GENERATED by tools/assetplace/gen_accessory_fit.py from Assets/blender/character/AST-081_offsets.json.")
    w("-- Do not edit by hand: change the source and rerun. TASK-089 (AST-081 customer accessories, AST-076 masks).")
    w("-- Kit: ReplicatedStorage.Assets.Crew.Accessories/<kit name> (tools/assetplace/build_kits.luau).")
    w("-- Fit per Content.Species key, applied by CrewRig.Build on the rest pose (studs, Roblox axes):")
    w("--   Use = kit piece actually worn (hard hat with or without ear slots); Offset = move; Scale = Size factor about")
    w("--   Pivot (HatAttachment); Forbidden = the piece does not fit this species (CrewRig skips it, warns once).")
    w("-- Missing entry = the mesh as exported. PROVISIONAL: measured by mesh overlap in Blender, not yet seen in Studio.")
    w("")
    w("export type Piece = { Asset: string, Anchor: string, Attachment: string, Only: string? }")
    w("export type Fit = { Use: string?, Offset: Vector3?, Scale: Vector3?, Forbidden: string? }")
    w("export type AccessoryFit = {")
    w("\tPivot: Vector3,")
    w("\tPieces: { [string]: Piece },")
    w("\tSpecies: { [string]: { [string]: Fit } },")
    w("}")
    w("")
    w("const fit: AccessoryFit = {")
    w(f"\tPivot = {vec(list(PIVOT))},")
    w("\tPieces = { -- kit name -> asset (_asset_ids.json key), R6 anchor, attachment of the sheet")
    for name in sorted(pieces):
        p = pieces[name]
        kit = p.get("kit_name", name)
        if kit != name:
            problems.append(f"{name}: kit_name {kit} differs from the key")
        anchor = p.get("anchor")
        base = name.removesuffix("_Mirror")
        if base in HAND:
            want = HAND[base] if base == name else HAND[base].replace("Right", "Left")
            if anchor != want:
                problems.append(f"{name}: anchor {anchor!r}, must be {want!r}")
        if anchor not in R6:
            problems.append(f"{name}: anchor {anchor!r} is not an R6 part")
        only = ""
        primary = p.get("primary_species")
        if primary and name.endswith("_" + primary):
            if primary not in key_of:
                problems.append(f"{name}: unknown species {primary}")
            else:
                only = f", Only = {lua_str(key_of[primary])}"
        w(
            f"\t\t{name} = {{ Asset = {lua_str(p['file'])}, Anchor = {lua_str(anchor or '')}, "
            f"Attachment = {lua_str(p.get('attachment', ''))}{only} }},"
        )
    w("\t},")
    w("\tSpecies = { -- Content.Species key -> kit name -> fit (non-default entries only)")
    species: dict = data["species"]
    unknown = set(species) - set(key_of)
    if unknown:
        problems.append(f"species without a Content.Species key: {sorted(unknown)}")
    missing = set(key_of) - set(species)
    if missing:
        problems.append(f"Content.Species without a fit entry: {sorted(missing)}")
    for asset in sorted(species, key=lambda a: key_of.get(a, a)):
        fits: dict = species[asset]
        entries: list[str] = []
        for name in sorted(fits):
            f = fits[name]
            if "ok" not in f:
                continue  # informative only (backpack tail overlap)
            if name not in pieces:
                problems.append(f"{asset}.{name}: not a kit piece")
            if not f["ok"]:
                sc = f.get("scale")
                why = f.get("why") or (
                    f"needs scale X {num(sc[0])}, not recommended" if sc and abs(sc[0] - 1) > 1e-6 else "does not fit"
                )
                entries.append(f"{name} = {{ Forbidden = {lua_str(why)} }}")
                continue
            parts: list[str] = []
            use = f.get("use")
            if use is not None:
                if use not in pieces:
                    problems.append(f"{asset}.{name}: use {use} is not a kit piece")
                if name == HARD_HAT:
                    want = HARD_HAT if asset in CAP_PLAIN else EARS_UP_HAT
                    if use != want:
                        problems.append(f"{asset}: hard hat {use} disagrees with the cap (expected {want})")
                if use != name:
                    parts.append(f"Use = {lua_str(use)}")
            off = f.get("offset")
            if off and any(abs(x) > 1e-6 for x in off):
                parts.append(f"Offset = {vec(off)}")
            sc = f.get("scale")
            if sc and any(abs(x - 1) > 1e-6 for x in sc):
                parts.append(f"Scale = {vec(sc)}")
            if parts:
                entries.append(f"{name} = {{ {', '.join(parts)} }}")
        key = key_of.get(asset, asset.lower())
        w(f"\t\t{key} = {{ {', '.join(entries)} }}," if entries else f"\t\t{key} = {{}},")
    w("\t},")
    w("}")
    w("")
    w("for _, p in fit.Pieces do")
    w("\ttable.freeze(p)")
    w("end")
    w("for _, s in fit.Species do")
    w("\tfor _, f in s do")
    w("\t\ttable.freeze(f)")
    w("\tend")
    w("\ttable.freeze(s)")
    w("end")
    w("table.freeze(fit.Pieces)")
    w("table.freeze(fit.Species)")
    w("return table.freeze(fit)")
    w("")

    if problems:
        raise SystemExit("gen_accessory_fit: " + "; ".join(problems))
    return "\n".join(lines)


def main() -> None:
    text = build()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run tools/assetplace/gen_accessory_fit.py")
            sys.exit(1)
        print("AccessoryFit up to date")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Pack icons into one atlas (<= 1024x1024) and emit a Luau map of ImageRectOffset/ImageRectSize.

  python atlas.py out/icons/*.png -o hud_icons.png --luau HudIcons.luau [--pad 4] [--max 1024]

One upload instead of N, and all icons load together (no pop-in). Shelf packing, tallest first.
In Luau: Image = ATLAS_ID, ImageRectOffset = map.name.offset, ImageRectSize = map.name.size.
Keep icons white so one atlas serves every tint (ImageColor3).
"""
from __future__ import annotations

import argparse
import glob
from pathlib import Path

from PIL import Image


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("inputs", nargs="+")
    ap.add_argument("-o", "--out", required=True)
    ap.add_argument("--luau", required=True)
    ap.add_argument("--pad", type=int, default=4)
    ap.add_argument("--max", type=int, default=1024)
    a = ap.parse_args()

    files = sorted({Path(f) for pat in a.inputs for f in glob.glob(pat)})
    imgs = [(f.stem, Image.open(f).convert("RGBA")) for f in files]
    imgs.sort(key=lambda t: t[1].height, reverse=True)
    x = y = shelf = 0
    W = a.max
    places = {}
    for name, im in imgs:
        w, h = im.width + a.pad * 2, im.height + a.pad * 2
        if w > W:
            raise SystemExit(f"{name} wider than atlas ({im.width}px)")
        if x + w > W:
            x, y, shelf = 0, y + shelf, 0
        places[name] = (x + a.pad, y + a.pad, im)
        x += w
        shelf = max(shelf, h)
    H = y + shelf
    if H > a.max:
        raise SystemExit(f"atlas would be {W}x{H} > {a.max}: split into two atlases or shrink icons")
    atlas = Image.new("RGBA", (W, H), (255, 255, 255, 0))
    lines = ["--!strict", f"-- Generated by atlas.py from {len(imgs)} icons. Atlas image: {Path(a.out).name}",
             "export type Rect = { offset: Vector2, size: Vector2 }", "", "return {"]
    for name in sorted(places):
        px, py, im = places[name]
        atlas.paste(im, (px, py))
        lines.append(f"\t[\"{name}\"] = {{ offset = Vector2.new({px}, {py}), size = Vector2.new({im.width}, {im.height}) }},")
    lines.append("} :: { [string]: Rect }")
    atlas.save(a.out)
    Path(a.luau).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {a.out} ({W}x{H}) and {a.luau} ({len(places)} icons)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
